import asyncio, datetime as dt, json
from playwright.async_api import async_playwright
def ts(days): return (dt.datetime.now()+dt.timedelta(days=days)).strftime('%Y-%m-%dT%H:%M')
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch()
        pg = await b.new_page(viewport={'width':1360,'height':900})
        errs=[]; pg.on('pageerror', lambda e: errs.append(str(e)))
        pg.on('console', lambda m: errs.append(m.text) if m.type=='error' else None)
        # 1. real login (wrong password first)
        await pg.goto('http://localhost:5173/login')
        await pg.fill('#email','officer@demo.bcvp.test'); await pg.fill('#password','wrong-password-1'); await pg.click('button[type=submit]')
        await pg.wait_for_selector('[role=alert]'); print('bad login message:', await pg.inner_text('[role=alert]'))
        await pg.fill('#password','Project@2026'); await pg.click('button[type=submit]')
        await pg.wait_for_url('**/officer'); await pg.wait_for_selector('dl[aria-label=Summary]')
        print('summary:', (await pg.inner_text('dl[aria-label=Summary]')).replace('\n',' | '))
        await pg.screenshot(path='/home/claude/s_dash.png')
        # 2. session survives reload (refresh cookie)
        await pg.reload(); await pg.wait_for_selector('dl[aria-label=Summary]'); print('session restored after reload: ok')
        # 3. tenders list + create with validation errors
        await pg.click('nav[aria-label="Main navigation"] >> text=Tenders'); await pg.wait_for_selector('table')
        print('list rows:', await pg.locator('tbody tr').count())
        await pg.click('text=Create tender'); await pg.click('button:has-text("Create tender")')
        await pg.wait_for_selector('.field-error'); print('empty-form errors:', await pg.locator('.field-error').count())
        await pg.fill('#tenderNo','BCVP/DEMO/MM/2026/014'); await pg.fill('#title','Duplicate number test tender'); await pg.fill('#department','Materials')
        await pg.fill('#estimatedValue','1000000'); await pg.fill('#submissionDeadline',ts(5)); await pg.fill('#bidOpeningDate',ts(6))
        await pg.set_input_files('#file','/home/claude/nit.pdf'); await pg.click('button:has-text("Create tender")')
        await pg.wait_for_selector('[role=alert]'); print('server duplicate message:', (await pg.inner_text('form [role=alert] >> nth=0')))
        await pg.fill('#tenderNo','BCVP/DEMO/E2E/2026/001'); await pg.fill('#title','E2E Supply of Gate Valves (Demo)')
        await pg.click('button:has-text("Create tender")'); await pg.wait_for_url('**/officer/tenders/*')
        await pg.wait_for_selector('text=Eligibility requirements'); print('created, detail heading:', await pg.inner_text('h1'))
        # 4. requirements: add two rows, one invalid
        await pg.click('button:has-text("Add requirement")'); await pg.click('button:has-text("Add requirement")')
        codes = pg.locator('input[id^=c]'); await codes.nth(0).fill('REQ-01'); await codes.nth(1).fill('REQ-02')
        descs = pg.locator('textarea[id^=d]'); await descs.nth(0).fill('Valid GST registration certificate'); await descs.nth(1).fill('Certificate valid on bid opening date')
        tmpl = pg.locator('select[id^=tp]'); await tmpl.nth(0).select_option('document_present'); await tmpl.nth(1).select_option('date_valid_on')
        rules = pg.locator('textarea[id^=r]')
        bad = json.dumps({'type':'date_valid_on','docType':'NOT_A_TYPE','dateField':'valid_upto','onDate':'bid_opening_date'})
        await rules.nth(1).fill(bad)
        await pg.click('button:has-text("Save draft")'); await pg.wait_for_selector('text=Draft saved')
        print('draft saved; badge:', await pg.inner_text('text=Draft – not in force'))
        await pg.click('button:has-text("Approve and freeze")'); await pg.click('button:has-text("Confirm approval")')
        await pg.wait_for_selector('fieldset ul[role=alert]'); print('approval rejected with:', await pg.inner_text('fieldset ul[role=alert]'))
        await pg.screenshot(path='/home/claude/s_reqerr.png', full_page=True)
        # fix and approve
        await rules.nth(1).fill(json.dumps({'type':'date_valid_on','docType':'UDYAM_CERTIFICATE','dateField':'valid_upto','onDate':'bid_opening_date'}))
        await pg.click('button:has-text("Save draft")'); await pg.wait_for_selector('text=Draft saved')
        await pg.click('button:has-text("Approve and freeze")'); await pg.click('button:has-text("Confirm approval")')
        await pg.wait_for_selector('text=approved and frozen'); print('approval message:', await pg.inner_text('p[role=status]'))
        await pg.wait_for_selector('text=Approved and frozen'); await pg.wait_for_timeout(600)
        print('tender badge now:', (await pg.inner_text('h1 + span')))
        print('editing controls after approval:', await pg.locator('button:has-text("Save draft")').count(), '| edit-new-version button:', await pg.locator('button:has-text("starts a new version")').count())
        await pg.screenshot(path='/home/claude/s_detail.png', full_page=True)
        # 5. logout, then API is really closed
        await pg.click('text=Log out'); await pg.wait_for_url('**/login'); await pg.goto('http://localhost:5173/officer'); await pg.wait_for_url('**/login'); print('after logout /officer redirects to login: ok')
        print('console/page errors:', [e for e in errs if 'Failed to load resource' not in e])
        await b.close()
asyncio.run(main())
